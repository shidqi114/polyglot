export interface TopicPhrase {
  /** Written Japanese, with its punctuation. */
  jp: string;
  /** Reading in kana, without punctuation. Used for audio, and checked against kuromoji by the tests. */
  kana: string;
  /** The Japanese in tiles for the build quiz. Joined, they make jp without punctuation. */
  tiles: string[];
  en: string;
}

export interface Topic {
  id: TopicId;
  title: string;
  group: TopicGroup;
  blurb: string;
  phrases: TopicPhrase[];
  /** Grammar point ids from grammar.ts and grammar-n4.ts that this topic uses. */
  grammar: string[];
  /** Story ids from stories.ts that this topic leads to. */
  stories: string[];
}

